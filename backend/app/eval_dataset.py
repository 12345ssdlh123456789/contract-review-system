# ==========================================================
#  评测集 —— 整个项目里最值钱的东西
# ----------------------------------------------------------
#  为什么必须先有评测集：
#  没有评测集，你改 prompt 全靠"感觉好像变好了"。
#  有了评测集，改完一跑，62% → 91%，这才是能拿给老板看的东西。
#
#  造法：
#  1. 按合同类型生成模板（采购/服务/租赁/保密）
#  2. 每份故意埋 2–4 个已知风险点（这就是 ground truth）
#  3. 人工标注「风险点 → 应给出的意见类型」
#  4. 跑分只看两个数：召回率（埋的雷抓到几个）、误报率（正常条款被误判几个）
#
#  企业取舍很明确：宁可误报，不可漏报。
#  所以召回率优先，误报用「低置信度不展示」来控制。
# ==========================================================
from dataclasses import dataclass, field


@dataclass
class PlantedRisk:
    """埋进去的风险点 = 标准答案。"""
    clause_no: int
    category: str
    level: str
    keywords: list[str]  # 命中任一即算抓到（宽松匹配，避免措辞差异误判）


@dataclass
class EvalCaseData:
    case_id: str
    contract_type: str
    title: str
    clauses: list[tuple[str, str]]  # (heading, content)
    risks: list[PlantedRisk] = field(default_factory=list)

    @property
    def content(self) -> str:
        lines = [f"{h}" for h, _ in self.clauses]
        out = []
        for heading, body in self.clauses:
            out.append(heading)
            if body:
                out.append(body)
            out.append("")
        return "\n".join(out).strip()

    @property
    def normal_clause_count(self) -> int:
        return max(1, len(self.clauses) - len(self.risks))


